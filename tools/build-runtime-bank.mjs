import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const root = process.cwd()
const sourcePath = path.join(root, 'data', 'vocabulary.json')
const outputPath = path.join(root, 'supabase', 'functions', 'generate-challenge', 'reviewed-bank.generated.ts')
const checkOnly = process.argv.includes('--check')

const vocabulary = JSON.parse(fs.readFileSync(sourcePath, 'utf8'))
const failures = []

const bank = vocabulary
  .filter(item => item.enabled !== false)
  .map((item, index) => {
    const label = item.word || item.id || `row ${index + 1}`
    const examples = Array.isArray(item.examples) ? item.examples : []
    const approvedExamples = examples.filter(example =>
      example?.reviewStatus === 'approved' &&
      String(example.en || '').trim() &&
      String(example.zhTw || '').trim() &&
      String(example.target || '').trim()
    )

    if (item.contentReview?.status !== 'approved') {
      failures.push(`${label}: contentReview.status 不是 approved`)
    }
    if (approvedExamples.length !== 3) {
      failures.push(`${label}: 核准例句應為 3 句，實際為 ${approvedExamples.length} 句`)
    }
    if (!String(item.word || '').trim() || !String(item.zh || '').trim()) {
      failures.push(`${label}: 缺少單字或中文`)
    }

    return {
      word: String(item.word || '').trim().toLowerCase(),
      zh: String(item.zh || '').trim(),
      topic: String(item.topic || 'General').trim(),
      grade: Number(item.grade) || 3,
      difficultyLevel: Number(item.difficultyLevel) || Number(item.grade) || 3,
      difficultyBand: item.difficultyBand || 'foundation',
      chunks: Array.isArray(item.chunks) && item.chunks.length
        ? item.chunks.map(chunk => String(chunk))
        : [...String(item.word || '').trim().toLowerCase()],
      phonetic: String(item.phonetic || '').trim(),
      examples: approvedExamples.map(example => ({
        id: String(example.id || ''),
        en: String(example.en).trim(),
        zhTw: String(example.zhTw).trim(),
        target: String(example.target).trim().toLowerCase(),
        reviewStatus: 'approved'
      }))
    }
  })

if (failures.length) {
  console.error(`Runtime bank validation failed (${failures.length}):`)
  failures.slice(0, 30).forEach(message => console.error(`- ${message}`))
  process.exit(1)
}

const sourceStat = fs.statSync(sourcePath)
const version = `cp38-${bank.length}-${sourceStat.size}`
const generated = `// AUTO-GENERATED by tools/build-runtime-bank.mjs. Do not edit manually.\n` +
  `export const REVIEWED_BANK_VERSION = ${JSON.stringify(version)}\n` +
  `export const REVIEWED_BANK_DATA = ${JSON.stringify(bank, null, 2)} as const\n`

if (checkOnly) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== generated) {
    console.error('Runtime bank is out of date. Run: npm run build:runtime-bank')
    process.exit(1)
  }
  console.log(`Runtime bank OK: ${bank.length} words, 3 approved examples each (${version})`)
  process.exit(0)
}

fs.writeFileSync(outputPath, generated, 'utf8')
console.log(`Generated ${path.relative(root, outputPath)}: ${bank.length} words (${version})`)
